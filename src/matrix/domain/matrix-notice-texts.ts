export type MatrixTextKey = keyof (typeof texts)['en'];

/** A notice text in the room's language (the workspace's default language), English otherwise. */
export function matrixText(lang: string | null | undefined, key: MatrixTextKey, vars: Record<string, string | number> = {}): string {
  const table = lang && lang in texts ? texts[lang as keyof typeof texts] : texts.en;
  const template: string = table[key] ?? texts.en[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}
