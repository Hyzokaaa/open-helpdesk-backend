import { DomainValidationError, InvalidCredentialsError } from '../../../shared/domain/errors';
import { TokenService } from '../../../shared/domain/token-service';
import { UserSessionRepository } from '../repositories/user-session.repository';
import { ResolveHandoffAudience } from './user-session-handoff-audience';
import { newTokenId } from './user-token-consume';

export const SESSION_HANDOFF_TYPE = 'session-handoff';

/** The code travels in a redirect URL and is traded at once, so it lives just long enough for that. */
const HANDOFF_CODE_TTL = '30s';

/** A PKCE S256 challenge: the base64url SHA-256 of the receiver's secret, 43 characters. */
const CODE_CHALLENGE = /^[A-Za-z0-9_-]{43}$/;

interface IssueSessionHandoffProps {
  userId: string;
  /** The session asking; absent on tokens from the API token exchange, which cannot be handed over. */
  sessionId?: string;
  /** Origin that will receive the session, e.g. https://help.example.com. */
  audience: string;
  /** Challenge generated by the receiver, which alone holds the secret that trades the code. */
  codeChallenge: string;
  /** Origin the request came from, kept for the audit log. */
  fromOrigin?: string | null;
  now?: Date;
}

/**
 * Lets a signed-in browser carry its session to another address of the installation without
 * typing the password again. Issues a single-use code that only the given origin can trade, and
 * only with the secret behind the challenge, so a code leaked through a URL is useless.
 *
 * Only a session kept signed in travels: one that must end with the browser would otherwise
 * survive it in the copy left on another address.
 */
export class IssueSessionHandoff {
  constructor(
    private readonly tokenService: TokenService,
    private readonly sessionRepository: UserSessionRepository,
    private readonly resolveAudience: ResolveHandoffAudience,
  ) {}

  async execute(props: IssueSessionHandoffProps): Promise<string> {
    const now = props.now ?? new Date();
    if (!props.sessionId) throw new InvalidCredentialsError('This sign-in cannot be carried to another address');

    const session = await this.sessionRepository.findById(props.sessionId);
    if (!session || session.userId !== props.userId || session.revokedAt || session.expiresAt <= now) {
      throw new InvalidCredentialsError('Invalid session');
    }
    if (!session.rememberMe) throw new DomainValidationError('Only a session kept signed in can be carried to another address');
    if (!CODE_CHALLENGE.test(props.codeChallenge)) throw new DomainValidationError('Invalid code challenge');
    if (!(await this.resolveAudience.execute(props.audience))) {
      throw new DomainValidationError('This address does not belong to the installation');
    }

    return this.tokenService.sign(
      {
        sub: props.userId,
        sid: session.getId(),
        aud: props.audience,
        cc: props.codeChallenge,
        from: props.fromOrigin ?? null,
        type: SESSION_HANDOFF_TYPE,
        jti: newTokenId(),
      },
      { expiresIn: HANDOFF_CODE_TTL },
    );
  }
}
